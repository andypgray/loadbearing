    private static void Delete(params string[] paths)
    {
        foreach (string path in paths)
            if (File.Exists(path))
                File.Delete(path);
    }

    // Every file a render in this class can write. A new render target reaches every row by arriving
    // here, rather than in fifteen argument lists that each state a subset no test actually claims.
    private static void DeleteRenderTargets()
    {
        Delete(RootAgents, ScopeAgents, WebAgents, DomainAgents, Architecture);
    }
