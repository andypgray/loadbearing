        (CliResult second, long secondLoads) = await RenderAsync(cache.Root, "--no-cache");

        firstLoads.ShouldBe(1);
        secondLoads.ShouldBe(1); // no read — and the flag is what makes render behave as it always did
        cache.HasCacheFile()
