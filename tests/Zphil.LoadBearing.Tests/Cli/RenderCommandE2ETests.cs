    [Fact]
    public async Task Render_Fresh_WritesPinnedRootAndScopeFilesAndNoLayerCards()
    {
        // Web is deleted alongside the ones under test because its absence is half the claim: MyAppRenderSpec
        // declares Domain and Web layers but anchors no rule on either, so every file render does emit here
        // is a *scope* card — the billing quarantine's and the domain caution's — and never a layer card. Web
        // also carries a Purpose, which the root block's module-map row renders and which still earns it no
        // card: a purpose describes a layer, and only an anchored rule places one. Domain gets a file all the
        // same, and that is the distinction: it is there for the scope that covers RetryPolicy, not for the
        // layer that shares its directory.
        DeleteRenderTargets();

        CliResult result = await CliRunner.InvokeAsync("render", CliRunner.MyAppSolution, "--spec", CliRunner.RenderSpecDll);

        result.ShouldSucceed();
        result.Out.NormalizedTrimmed()
            .ShouldBe("wrote AGENTS.md\nwrote MyApp.Legacy.Billing/AGENTS.md\nwrote MyApp.Domain/AGENTS.md");
        File.ReadAllText(RootAgents)
            .ShouldBe(Wrap(RootBody, "\n"));
        File.ReadAllText(ScopeAgents)
            .ShouldBe(Wrap(ScopeBody, "\n"));
        File.ReadAllText(DomainAgents)
            .ShouldBe(Wrap(DomainCautionBody, "\n"));
        File.Exists(WebAgents)
            .ShouldBeFalse();
    }

