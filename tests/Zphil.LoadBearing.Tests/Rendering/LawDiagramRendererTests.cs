    // One spec carrying every construct the fence can draw: two layers, a ban between them, an exposure
    // ban out of the solution, an only-verb naming its own subject, a Migrate rule into a single type, a
    // naming rule with no direction, and a quarantined scope with one facade.
    private static ArchitectureModel WholeDrawingSpec()
    {
        return Checker.Model(arch =>
        {
            Layer domain = arch.Layer("Domain", "Shop.Domain.*");
            Layer web = arch.Layer("Web", "Shop.Web.*");

            arch.Rule("layering/domain-independent")
                .Enforce(domain.MustNotReference(web))
                .Because("The domain outlives whatever delivers it.");

            arch.Rule("api/no-engine-types")
                .Enforce(web.MustNotExpose(arch.Namespace("Vendor.Engine.*")))
                .Because("An engine type on a public signature forces every consumer to compile against it.");

            arch.Rule("packs/leaf")
                .Enforce(arch.Namespace("Shop.Pack.*").MustOnlyReference(arch.Namespace("Shop.Pack.*"), domain))
                .Because("A pack that reaches past the domain drags the tool into its consumers.");

            arch.Rule("data/no-inline-sql")
                .Migrate(
                    "Controllers build DataTables inline.",
                    arch.Namespace("Shop.Web.Controllers.*").MustNotReference(typeof(DataTable)))
                .Because("Repository pattern for testability.");

            arch.Rule("naming/interfaces")
                .Enforce(arch.Types.OfKind(TypeKind.Interface).MustHavePrefix("I"))
                .Because("`I*` stays a reliable grep for the seams.");

            arch.Scope("legacy/pricing")
                .Quarantine(arch.Namespace("Shop.Legacy.Pricing.*"))
                .BoundaryOnlyVia(typeof(IPricingFacade))
                .Dragons("Rounding happens at line-item level.")
                .Because("Replacement scheduled; not worth stabilizing.");
        });
    }

    // The same scope with no sanctioned surface at all: the degenerate quarantine, which is both a bare
    // rectangle and a rule whose tripwire draws nothing.
    private static ArchitectureModel HermeticScopeSpec()
    {
        return Checker.Model(arch =>
            arch.Scope("legacy/pricing")
                .Quarantine(arch.Namespace("Shop.Legacy.Pricing.*"))
                .Dragons("Rounding happens at line-item level.")
                .Because("x"));
    }

    // Just the edge lines, which is what a direction or posture pin is about.
    private static IReadOnlyList<string> Edges(string block)
    {
        return MermaidBlock.Diagram(block)
            .Where(line => !line.StartsWith("l_", StringComparison.Ordinal))
            .Where(line => line.Contains("--x", StringComparison.Ordinal)
                           || line.Contains("-->", StringComparison.Ordinal)
                           || line.Contains("-.-x", StringComparison.Ordinal))
            .ToList();
    }

    // Every emitted node ID, however it is shaped.
    private static IReadOnlyList<string> IdsIn(string block)
    {
        return MermaidBlock.Diagram(block)
            .Select(line => line.StartsWith("subgraph ", StringComparison.Ordinal) ? line.Substring(9) : line)
            .Select(line => new string(line.TakeWhile(character => character is '_' or >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9')
                .ToArray()))
            .Where(id => id.Length > 0)
            .ToList();
    }

    /// <summary>A sanctioned surface for the quarantine pins; only its name reaches the drawing.</summary>
    private interface IPricingFacade;

    /// <summary>The second facade, so Boundary order is observable.</summary>
    private sealed class PricingFacade : IPricingFacade;
