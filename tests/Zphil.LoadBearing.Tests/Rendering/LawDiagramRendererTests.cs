    [Fact]
    public void Block_TheTwoBanVerbs_PointInOppositeDirections()
    {
        // Arrange — the same two places, said from each end.
        ArchitectureModel model = Checker.Model(arch =>
        {
            arch.Rule("r/out")
                .Enforce(arch.Namespace("A.*").MustNotReference(arch.Namespace("B.*")))
                .Because("x");
            arch.Rule("r/in")
                .Enforce(arch.Namespace("C.*").MustNotBeReferencedBy(arch.Namespace("D.*")))
                .Because("x");
        });

        // Act
        string block = LawDiagramRenderer.Block(model, SpecName);

        // Assert — MustNotBeReferencedBy is the inbound voice: the operand is the source of the arrow.
        Edges(block)
            .ShouldBe(["s_A --x s_B", "s_D --x s_C"]);
    }

    [Fact]
    public void Block_TheTwoOnlyVerbs_DrawAllowEdgesAndOmitTheSelfTarget()
    {
        // Arrange — both verbs name their own subject in the allowed list, which is the permission for a
        // place to reference itself.
        ArchitectureModel model = Checker.Model(arch =>
        {
            arch.Rule("r/out")
                .Enforce(arch.Namespace("A.*").MustOnlyReference(arch.Namespace("A.*"), arch.Namespace("B.*")))
                .Because("x");
            arch.Rule("r/in")
                .Enforce(arch.Namespace("C.*").MustOnlyBeReferencedBy(arch.Namespace("C.*"), arch.Namespace("D.*")))
                .Because("x");
        });

        // Act
        string block = LawDiagramRenderer.Block(model, SpecName);

        // Assert
        Edges(block)
            .ShouldBe(["s_A -->|\"only\"| s_B", "s_D -->|\"only\"| s_C"]);
    }

